def feature_catalog(root):
    path = Path(root) / FEATURE_CATALOG
    if not path.is_file():
        return {"format": FEATURE_FORMAT, "features": []}
    value = load(path)
    problems = Validator(FEATURE_SCHEMA).errors(value)
    if problems:
        raise ValueError(f"{FEATURE_CATALOG} invalid at {problems[0][0] or '/'}: {problems[0][1]}")
    return value


DEFAULT_PROFILE = {"format": PROFILE_FORMAT, "name": "aeion-factory", "max_bytes": 12000,
                   "frontmatter_order": ["id", "sequence", "title", "goal", "area", "size", "phase", "parallel",
                                         "write_paths", "depends_on", "status", "spec_sha256", "generated_by"]}


RESERVED_ROW = frozenset({"id", "goal", "file", "spec_sha256", "generated_by"})


def export(root, model, goal_id, everything, profile_path, out):
    """Write one feature Markdown per goal (eight spec sections), fail on any size or content violation."""
    try:
        catalog = feature_catalog(root)
        profile = dict(DEFAULT_PROFILE)
        if profile_path:
            loaded = load(profile_path)
            problems = Validator(PROFILE_SCHEMA).errors(loaded)
            if problems:
                raise ValueError(f"profile invalid at {problems[0][0] or '/'}: {problems[0][1]}")
            profile.update(loaded)
    except (ValueError, InputError) as error:
        print(f"export: {error}")
        return 4
    entries = {f["goal_id"]: f for f in catalog["features"]}
    goals = sorted(n["id"] for n in model.spec["nodes"] if n["kind"] == "Goal" and n["status"] != "retired")
    chosen = goals if everything else [goal_id] if goal_id else []
    if not chosen:
        print("export: name --goal GOAL-ID or --all")
        return 2
    out = Path(out) if out else Path(root) / "docs/features"
    rows, failures = [], []
    for gid in chosen:
        if gid not in model.nodes or model.nodes[gid]["kind"] != "Goal":
            failures.append(f"{gid}: not a goal in the spec")
            continue
        entry = entries.get(gid) or {"goal_id": gid, "number": gid.split("-")[1][-3:], "slug": _slug(model.nodes[gid]["title"])}
        text, row = feature_markdown(model, gid, entry, entries, profile)
        size = len(text.encode("utf-8"))
        if size > profile["max_bytes"]:
            failures.append(f"{gid}: {size} bytes exceeds the profile limit of {profile['max_bytes']}; split the goal")
            continue
        if "- [ ] " not in text:
            failures.append(f"{gid}: no acceptance check: link at least one TestCase that verifies its requirements")
            continue
        broken = structure_problems(text)
        if broken:
            failures.append(f"{gid}: {broken[0]}")
            continue
        if Path(row["file"]).name != row["file"] or not row["file"].endswith(".md"):
            failures.append(f"{gid}: file name {row['file']!r} is not a plain .md name")
            continue
        write_atomic(out / row["file"], text)
        rows.append(row)
        print(f"wrote {out / row['file']} ({size} bytes)")
    if rows:
        write_atomic(out / "features.json", pretty({"format": "aeion-feature-export/0.1", "profile": profile["name"],
                                                    "spec_sha256": model.digest, "features": rows}))
    for failure in failures:
        print(f"export: FAIL {failure}")
    return 2 if failures else 0


def _slug(title):
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:60] or "feature"


SECTIONS = ["## Intent", "## Data sources", "## Inputs", "## Outputs", "## Invariants", "## Determinism",
            "## Acceptance checks", "## Out of scope"]


def _flat(value):
    """Every string on one line: a value can never open a heading, list item or check of its own."""
    if isinstance(value, str):
        return " ".join(value.split())
    if isinstance(value, list):
        return [_flat(v) for v in value]
    if isinstance(value, dict):
        return {k: _flat(v) for k, v in value.items()}
    return value


def structure_problems(text):
    """The eight sections in order, once each, and checklist items only under Acceptance checks."""
    headings = [line for line in text.split("\n") if line.startswith("## ")]
    problems = [] if headings == SECTIONS else [f"sections are {headings}, expected {SECTIONS}"]
    section = None
    for line in text.split("\n"):
        section = line if line.startswith("## ") else section
        if line.startswith("- [ ] ") and section != "## Acceptance checks":
            problems.append(f"a checklist item outside Acceptance checks: {line[:60]}")
    return problems


def feature_markdown(model, goal_id, entry, entries, profile):
    """(Markdown, manifest row) for one goal: its requirements and their closure, in the eight sections."""
    import copy
    model = copy.copy(model)
    model.nodes = {key: _flat(node) for key, node in model.nodes.items()}
    model.sources = {key: _flat(source) for key, source in model.sources.items()}
    model.envs = {key: _flat(env) for key, env in model.envs.items()}
    entry = _flat(entry)
    goal = model.nodes[goal_id]
    requirements = [model.nodes[r] for r in sorted(model.linked(goal_id, "satisfies", "in"))
                    if model.nodes[r]["status"] != "retired"]
    req_ids = {r["id"] for r in requirements}
    related = lambda relation: sorted({s for r in req_ids for s in model.linked(r, relation, "in")})  # noqa: E731
    terms = sorted({t for r in req_ids for t in model.linked(r, "uses_term")})
    constraints = [model.nodes[c] for c in related("formalizes")]
    tests = [model.nodes[t] for t in related("verifies")]
    scenarios = [model.nodes[s] for s in related("illustrates")]
    components = [model.nodes[c] for c in related("implements")]
    decisions = [model.nodes[d] for d in sorted({d for n in [goal_id, *req_ids, *(c["id"] for c in constraints)]
                                                 for d in model.linked(n, "governs", "in")})]
    numbers = {e["goal_id"]: e["number"] for e in entries.values()}
    derived = sorted({numbers.get(g) for r in req_ids for dep in model.linked(r, "depends_on")
                      for g in model.linked(dep, "satisfies") if g != goal_id and numbers.get(g)})
    depends = sorted(set(entry.get("depends_on", [])) | set(derived))
    number, title = entry["number"], entry.get("title") or goal["title"]
    row = {"id": number, "sequence": entry.get("sequence", int(number)), "title": title, "goal": goal_id,
           "area": entry.get("area", "core"), "size": entry.get("size", "M"), "phase": entry.get("phase", "P1"),
           "parallel": entry.get("parallel", False), "write_paths": entry.get("write_paths", []),
           "depends_on": depends, "status": "proposed", "spec_sha256": model.digest,
           "generated_by": GENERATOR, "file": f"{number}-{entry['slug']}.md"}
    # A profile adds catalog fields; it never changes the identity or the file name the export computed.
    row.update({k: v for k, v in profile.get("frontmatter", {}).items() if k not in RESERVED_ROW})
    front = ["---"]
    for key in profile["frontmatter_order"]:
        if key in row:
            front.append(f"{key}: {_yaml(row[key])}")
    front.append("---")
    lines = front + ["", f"# {number} — {title}", "", "## Intent", "",
                     f"{goal['data']['description']} Success measure: {goal['data']['success_measure']}", "",
                     f"Canonical source: `knowledge/spec/spec.json` {goal_id} (spec `{model.digest[:12]}`), requirements "
                     + (", ".join(sorted(req_ids)) or "none") + ".", "", "## Data sources", ""]
    sources = sorted({s for n in [goal, *requirements] for s in n["source_ids"]})
    lines += [f"- {s} ({model.sources[s]['type']}, {model.sources[s]['review_state']}): `{model.sources[s]['locator']}`"
              for s in sources if s in model.sources]
    envs = sorted({c["data"]["environment_id"] for c in constraints if c["data"]["environment_id"]})
    lines += [f"- {e}: {model.envs[e]['title']}" for e in envs if e in model.envs]
    if profile.get("data_sources_text"):
        lines += ["", profile["data_sources_text"]]
    lines += ["", "## Inputs", ""]
    if entry.get("delivery"):
        lines += ["**Delivery steps:**", ""] + [f"{i}. {step}" for i, step in enumerate(entry["delivery"], 1)] + [""]
    lines += ["**Requirements:**", ""]
    lines += [f"- {r['id']} ({r['data']['priority']}, risk {r['data']['risk']}): {render_requirement(r['data'])}"
              for r in requirements]
    if terms:
        lines += ["", "**Terms:**", ""]
        for t in terms:
            data = model.nodes[t]["data"]
            lines.append(f"- {t} {model.nodes[t]['title']}: {data['definition']}" + (f" Unit: {data['unit']}." if data["unit"] else ""))
    if decisions:
        lines += ["", "**Decisions:**", ""]
        lines += [f"- {d['id']} {d['data']['question']} -> " + (d["data"]["answer"] if d["data"]["answer"] is not None
                                                               else "OPEN (blocks design readiness)" if d["data"]["blocking"] else "open")
                  for d in decisions]
    lines += ["", "## Outputs", ""]
    refusals = [r for r in requirements if r["data"]["pattern"] == "unwanted"]
    lines += [f"- {c['id']} {c['title']}: {c['data']['responsibility']}" for c in components]
    lines += [f"- Refusal ({r['id']}): {r['data']['response']} when {r['data']['trigger']}." for r in refusals]
    if not components and not refusals:
        lines.append("- The observable responses of the requirements above.")
    if profile.get("outputs_text"):
        lines += ["", profile["outputs_text"]]
    lines += ["", "## Invariants", ""]
    checks = {c["id"]: sorted(model.linked(c["id"], "checks", "in")) for c in constraints}
    for c in constraints:
        data = c["data"]
        proof = ", ".join(checks[c["id"]]) or "no test yet"
        meaning = data["review_protocol"] if data["representation"] == "review_protocol" else "BCIR predicate in " + data["environment_id"]
        lines.append(f"- {c['id']} {c['title']} ({data['predicate_role']}, {data['classification']['strength']}): "
                     f"{meaning}; checked by {proof}.")
    if not constraints:
        lines.append("- No formal constraint yet: the acceptance checks below are the contract.")
    if profile.get("invariants_text"):
        lines += ["", profile["invariants_text"].replace("{id}", number)]
    lines += ["", "## Determinism", "", profile.get("determinism_text") or
              "Deterministic checks decide: the acceptance tests below and `tools/axiom/axiom validate`. A model's "
              "output is a proposal until those checks pass.", "", "## Acceptance checks", ""]
    for t in tests:
        verifies = ", ".join(sorted(set(model.linked(t["id"], "verifies")) & req_ids))
        lines.append(f"- [ ] {t['id']} ({t['data']['level']}, {'refusal' if t['data']['negative'] else 'normal'}) "
                     f"verifies {verifies}: {t['data']['oracle']}")
    scenario_text = entry.get("test_scenario") or " ".join(
        f"{s['id']} ({s['data']['intent']}) on {s['data']['event']}: {s['data']['expected']}" for s in scenarios)
    if scenario_text:
        lines += ["", f"**Test scenario:** {scenario_text}"]
    lines += ["", "## Out of scope", ""]
    lines += [f"- {item}" for item in entry.get("out_of_scope", [])] or ["- Anything not stated above; a new need is a new goal."]
    return "\n".join(lines).rstrip() + "\n", row


def _yaml(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, list):
        return "[" + ", ".join(json.dumps(v) if not re.fullmatch(r"[0-9]{3}", str(v)) else str(v) for v in value) + "]"
    text = str(value)
    return json.dumps(text) if re.search(r"[:#\[\]{},&*!|>'\"%@`]|^\s|\s$", text) or text == "" else text
