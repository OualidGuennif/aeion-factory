def md(value):
    """Escape a value for Markdown prose and tables: markup and raw HTML stay literal text."""
    text = str(value).replace("\\", "\\\\").replace("\r", " ").replace("\n", " ")
    for char in "`*_[]<>|#":
        text = text.replace(char, "\\" + char)
    return text


def anchor(node_id):
    return node_id.lower()


class Pages:
    """Every generated output for one spec snapshot, keyed by its project-relative path."""

    def __init__(self, root, model, result):
        self.root, self.model, self.result = Path(root), model, result
        self.spec = model.spec
        self.outputs = {}

    def node(self, node_id):
        return self.model.nodes[node_id]

    def ref(self, node_id, page):
        """A link to a canonical node's anchor on the page that owns its kind."""
        node = self.model.nodes.get(node_id)
        if node is None:
            return md(node_id)
        target = OWNER_PAGE.get(node["kind"], "product/requirements.md")
        relative = os.path.relpath(target, os.path.dirname(page) or ".").replace(os.sep, "/")
        return f"[{node_id}]({relative}#{anchor(node_id)})"

    def write(self, rel, lines):
        self.outputs[rel] = NOTICE + "\n\n" + "\n".join(lines).rstrip() + "\n"


OWNER_PAGE = {"Goal": "product/overview.md", "Requirement": "product/requirements.md", "Term": "product/terms.md",
              "Decision": "product/decisions.md", "Assumption": "product/decisions.md",
              "Constraint": "product/requirements.md", "StateModel": "product/requirements.md",
              "Component": "system/components.md", "Risk": "system/components.md", "Control": "system/components.md",
              "Scenario": "verification/index.md", "TestCase": "verification/index.md"}


def build_pages(root, model, result):
    """{path relative to docs/generated: Markdown} plus the cockpit and the diagrams."""
    pages = Pages(root, model, result)
    _overview(pages)
    _requirements(pages)
    _terms(pages)
    _decisions(pages)
    _components(pages)
    _verification(pages)
    _traceability(pages)
    _views(pages)
    return pages


def _overview(p):
    project, page = p.spec["project"], "product/overview.md"
    lines = [f"# {md(project['name'])}", "", md(project["description"]), "",
             f"Project `{project['id']}` · mode **{project['mode']}** · owner "
             f"{md(p.model.actors.get(project['owner'], {}).get('name', project['owner']))}",
             "", "## Goals", ""]
    for goal in sorted(p.model.spec["nodes"], key=lambda n: n["id"]):
        if goal["kind"] != "Goal":
            continue
        requirements = sorted(p.model.linked(goal["id"], "satisfies", "in"))
        lines += [f'<a id="{anchor(goal["id"])}"></a>', f"### {goal['id']} {md(goal['title'])} ({goal['status']})", "",
                  md(goal["data"]["description"]), "", f"Success measure: {md(goal['data']['success_measure'])}", "",
                  "Requirements: " + (", ".join(p.ref(r, page) for r in requirements) or "none yet"), ""]
    lines += ["## Actors", "", "| ID | Name | Type | Identity binding |", "| --- | --- | --- | --- |"]
    lines += [f"| {a['id']} | {md(a['name'])} | {a['type']} | {a['binding_status']} |" for a in p.spec["actors"]]
    lines += ["", "## Sources", "", "| ID | Type | Locator | Review state |", "| --- | --- | --- | --- |"]
    lines += [f"| {s['id']} | {s['type']} | {md(s['locator'])} | {s['review_state']} |" for s in p.spec["sources"]]
    p.write(page, lines)


def _requirements(p):
    page = "product/requirements.md"
    lines = ["# Requirements", "", "Rendered from structured fields (AX-M-006). The sentence is generated; "
             "change the fields in `knowledge/spec/spec.json`.", ""]
    goals = [n for n in p.spec["nodes"] if n["kind"] == "Goal"]
    seen = set()
    for goal in sorted(goals, key=lambda n: n["id"]) + [None]:
        if goal is None:
            members = [n for n in p.spec["nodes"] if n["kind"] == "Requirement" and n["id"] not in seen]
            if not members:
                break
            lines += ["## Not linked to a goal", ""]
        else:
            members = [p.node(r) for r in sorted(p.model.linked(goal["id"], "satisfies", "in"))]
            lines += [f"## {goal['id']} {md(goal['title'])}", ""]
        for requirement in members:
            seen.add(requirement["id"])
            lines += _requirement_block(p, requirement, page)
    constraints = [n for n in p.spec["nodes"] if n["kind"] == "Constraint"]
    if constraints:
        lines += ["## Constraints", "", "| ID | Title | Role | Strength | Scope | Formalizes |", "| --- | --- | --- | --- | --- | --- |"]
        for c in sorted(constraints, key=lambda n: n["id"]):
            data = c["data"]
            lines.append(f'| <a id="{anchor(c["id"])}"></a>{c["id"]} | {md(c["title"])} | {data["predicate_role"]} | '
                         f'{data["classification"]["strength"]} | {data["scope"]} | '
                         + ", ".join(p.ref(r, page) for r in sorted(p.model.linked(c["id"], "formalizes"))) + " |")
        lines.append("")
    models = [n for n in p.spec["nodes"] if n["kind"] == "StateModel"]
    for model_node in sorted(models, key=lambda n: n["id"]):
        data = model_node["data"]
        lines += [f'<a id="{anchor(model_node["id"])}"></a>', f"## {model_node['id']} {md(model_node['title'])}", "",
                  f"Initial state `{data['initial']}`; terminal: "
                  + ", ".join(f"`{s['name']}`" for s in data["states"] if s["terminal"]) + ".", "",
                  "| Transition | From | Event | Guard | To |", "| --- | --- | --- | --- | --- |"]
        lines += [f"| {t['id']} | {md(t['from'])} | {md(t['event'])} | {p.ref(t['guard_id'], page) if t['guard_id'] else '-'} "
                  f"| {md(t['to'])} |" for t in data["transitions"]]
        lines.append("")
    p.write(page, lines)


def _requirement_block(p, requirement, page):
    data, node_id = requirement["data"], requirement["id"]
    related = []
    for relation, label in (("uses_term", "Terms"), ("depends_on", "Depends on")):
        targets = sorted(p.model.linked(node_id, relation))
        if targets:
            related.append(f"{label}: " + ", ".join(p.ref(t, page) for t in targets))
    for relation, label in (("formalizes", "Constraints"), ("verifies", "Tests"), ("illustrates", "Scenarios"),
                            ("implements", "Components"), ("governs", "Decisions")):
        sources = sorted(p.model.linked(node_id, relation, "in"))
        if sources:
            related.append(f"{label}: " + ", ".join(p.ref(s, page) for s in sources))
    return [f'<a id="{anchor(node_id)}"></a>', f"### {node_id} {md(requirement['title'])}", "",
            f"> {md(render_requirement(data))}", "",
            f"{data['category']} · {data['priority']} · risk {data['risk']} · verification {data['verification_mode']} · "
            f"status {requirement['status']} · revision {requirement['revision']}", "",
            *[f"- {line}" for line in related], ""]


def _terms(p):
    lines = ["# Terms", "", "| ID | Term | Definition | Unit | Context |", "| --- | --- | --- | --- | --- |"]
    for term in sorted((n for n in p.spec["nodes"] if n["kind"] == "Term"), key=lambda n: n["id"]):
        data = term["data"]
        aliases = f" (also: {md(', '.join(data['aliases']))})" if data["aliases"] else ""
        lines.append(f'| <a id="{anchor(term["id"])}"></a>{term["id"]} | {md(term["title"])}{aliases} | '
                     f"{md(data['definition'])} | {md(data['unit'] or '-')} | {md(data['context'])} |")
    p.write("product/terms.md", lines)


def _decisions(p):
    page = "product/decisions.md"
    decisions = sorted((n for n in p.spec["nodes"] if n["kind"] == "Decision"),
                       key=lambda n: (n["data"]["answer"] is not None, n["id"]))
    lines = ["# Decisions and assumptions", "", "Open decisions come first. Silence is not approval (AX-G-004).", ""]
    for d in decisions:
        data = d["data"]
        state = "OPEN" if data["answer"] is None else "answered"
        governs = ", ".join(p.ref(t, page) for t in sorted(p.model.linked(d["id"], "governs")))
        lines += [f'<a id="{anchor(d["id"])}"></a>', f"## {d['id']} {md(d['title'])} ({state}"
                  f"{', blocking' if data['blocking'] else ''})", "", f"**Question:** {md(data['question'])}", "",
                  "**Options:** " + "; ".join(md(o) for o in data["options"]), "",
                  f"**Answer:** {md(data['answer']) if data['answer'] is not None else 'not decided'}", "",
                  f"**Rationale:** {md(data['rationale'])}", "", f"Governs: {governs or 'nothing linked'}", ""]
    assumptions = sorted((n for n in p.spec["nodes"] if n["kind"] == "Assumption"), key=lambda n: n["id"])
    if assumptions:
        lines += ["## Assumptions", "", "| ID | Claim | State | Blocking | Validation |", "| --- | --- | --- | --- | --- |"]
        lines += [f'| <a id="{anchor(a["id"])}"></a>{a["id"]} | {md(a["data"]["claim"])} | {a["data"]["state"]} | '
                  f'{"yes" if a["data"]["blocking"] else "no"} | {md(a["data"]["validation_method"])} |' for a in assumptions]
    p.write(page, lines)


def _components(p):
    page = "system/components.md"
    lines = ["# Components, risks and controls", ""]
    for c in sorted((n for n in p.spec["nodes"] if n["kind"] == "Component"), key=lambda n: n["id"]):
        implements = ", ".join(p.ref(r, page) for r in sorted(p.model.linked(c["id"], "implements")))
        bindings = [b for b in p.spec["bindings"] if b["node_id"] == c["id"]]
        lines += [f'<a id="{anchor(c["id"])}"></a>', f"## {c['id']} {md(c['title'])}", "",
                  md(c["data"]["responsibility"]), "", f"Boundary: {md(c['data']['boundary'])}", "",
                  f"Implements: {implements or 'none declared'}", ""]
        lines += [f"- {b['id']} {b['kind']} `{md(b['path'])}` symbol `{md(b['symbol'])}` ({b['expected_resolution']})"
                  for b in bindings]
        lines.append("")
    for kind in ("Risk", "Control"):
        nodes = sorted((n for n in p.spec["nodes"] if n["kind"] == kind), key=lambda n: n["id"])
        if not nodes:
            continue
        lines += [f"## {kind}s", ""]
        for n in nodes:
            data = n["data"]
            detail = (f"asset {md(data['asset'])}; threat {md(data['threat'])}; impact {md(data['impact'])}; "
                      f"severity {data['severity']}" if kind == "Risk" else
                      f"{md(data['description'])} Enforced at {md(data['enforcement_location'])}; verified by "
                      f"{md(data['verification'])}")
            lines += [f'<a id="{anchor(n["id"])}"></a>', f"- **{n['id']} {md(n['title'])}**: {detail}"]
        lines.append("")
    p.write(page, lines)


def _verification(p):
    page = "verification/index.md"
    lines = ["# Verification", "", "Gate results are computed from `knowledge/spec/spec.json` by `tools/axiom/axiom validate`. "
             "A planned test is not an executed one (AX-T-005).", "", "## Design gates", "",
             "| Gate | Subject | Result | Diagnostics |", "| --- | --- | --- | --- |"]
    for gate in DESIGN_GATES:
        count = sum(1 for d in p.result.diagnostics if d["gate"] == gate)
        lines.append(f"| {gate} | {GATE_TITLES[gate]} | {p.result.gate_status(gate)} | {count} |")
    open_items = sorted(p.result.diagnostics, key=lambda d: (d["gate"], d["subject_id"] or ""))[:40]
    if open_items:
        lines += ["", "| Gate | Code | Subject | Message |", "| --- | --- | --- | --- |"]
        lines += [f"| {d['gate']} | {d['code']} | {d['subject_id'] or '-'} | {md(d['message'])} |" for d in open_items]
    lines += ["", "## Test cases", "", "| ID | Title | Level | Case | State | Verifies | Oracle |",
              "| --- | --- | --- | --- | --- | --- | --- |"]
    for t in sorted((n for n in p.spec["nodes"] if n["kind"] == "TestCase"), key=lambda n: n["id"]):
        data = t["data"]
        verifies = ", ".join(p.ref(r, page) for r in sorted(p.model.linked(t["id"], "verifies")))
        lines.append(f'| <a id="{anchor(t["id"])}"></a>{t["id"]} | {md(t["title"])} | {data["level"]} | '
                     f'{"refusal" if data["negative"] else "normal"} | {data["state"]} | {verifies} | {md(data["oracle"])} |')
    lines += ["", "## Scenarios", "", "| ID | Title | Intent | Event | Expected |", "| --- | --- | --- | --- | --- |"]
    for s in sorted((n for n in p.spec["nodes"] if n["kind"] == "Scenario"), key=lambda n: n["id"]):
        data = s["data"]
        lines.append(f'| <a id="{anchor(s["id"])}"></a>{s["id"]} | {md(s["title"])} | {data["intent"]} | '
                     f'{md(data["event"])} | {md(data["expected"])} |')
    lines += ["", "## Evidence receipts", ""]
    receipts = _receipts(p.root)
    if not receipts:
        lines.append("No receipt in `knowledge/spec/evidence/`: no test of this plan has been executed through "
                     "`tools/axiom/axiom evidence run`.")
    else:
        lines += ["| Test | Result | Collected | Spec at execution | Matches current spec |", "| --- | --- | --- | --- | --- |"]
        for receipt in receipts:
            same = "yes" if receipt.get("spec_sha256") == p.model.digest else "no (stale)"
            lines.append(f"| {receipt.get('test_id', '?')} | {receipt.get('status', '?')} | "
                         f"{receipt.get('counts', {}).get('collected', 0)} | `{str(receipt.get('spec_sha256'))[:12]}` | {same} |")
        lines += ["", "Source-tree freshness is checked live by `tools/axiom/axiom evidence check`, not here."]
    p.write(page, lines)


def _receipts(root):
    folder = Path(root) / EVIDENCE_DIR
    found = []
    for path in sorted(folder.glob("*.json")) if folder.is_dir() else []:
        try:
            found.append(load(path))
        except InputError:
            found.append({"test_id": path.stem, "status": "unreadable"})
    return found


def _traceability(p):
    page = "traceability.md"
    lines = ["# Traceability", "", "Declared links only: a link records a claim, not behaviour (AX-P-006).", "",
             "| Goal | Requirement | Constraints | Tests | Components | Bindings |", "| --- | --- | --- | --- | --- | --- |"]
    for requirement in sorted((n for n in p.spec["nodes"] if n["kind"] == "Requirement"), key=lambda n: n["id"]):
        rid = requirement["id"]
        goals = ", ".join(p.ref(g, page) for g in sorted(p.model.linked(rid, "satisfies")))
        cons = ", ".join(p.ref(c, page) for c in sorted(p.model.linked(rid, "formalizes", "in")))
        tests = ", ".join(p.ref(t, page) for t in sorted(p.model.linked(rid, "verifies", "in")))
        comps = sorted(p.model.linked(rid, "implements", "in"))
        bindings = [b["id"] for b in p.spec["bindings"] if b["node_id"] in [rid, *comps]]
        lines.append(f"| {goals or '-'} | {p.ref(rid, page)} | {cons or '-'} | {tests or '-'} | "
                     f"{', '.join(p.ref(c, page) for c in comps) or '-'} | {', '.join(bindings) or '-'} |")
    p.write(page, lines)


def _views(p):
    catalog = views.catalog(p.root)
    lines = ["# Views", "", "Diagrams are documentation views, not canonical claims. Each states its claim: "
             "**proposed** (not accepted), **intended** (accepted target) or **observed** (backed by evidence).", ""]
    kinds = {"system": "System", "process": "Process", "sequence": "Sequence", "usecase": "Use cases",
             "state": "State", "domain": "Domain"}
    for kind, title in kinds.items():
        listed = [v for v in catalog["views"] if v["kind"] == kind]
        if not listed:
            continue
        lines += [f"## {title}", ""]
        lines += [f"- [{md(v['title'])}]({v['id']}.md): {md(v['question'])} *({v['claim']})*" for v in listed]
        lines.append("")
    for v in catalog["views"]:
        page = f"views/{v['id']}.md"
        ids = ", ".join(p.ref(i, page) for i in v["canonical_ids"]) or "none"
        unknown = [i for i in v["canonical_ids"] if i not in p.model.nodes]
        p.write(page, [f"# {md(v['title'])}", "", f"**Question:** {md(v['question'])}", "",
                       f"**Claim:** {v['claim']} · **Audience:** {md(v.get('audience') or 'everyone')} · "
                       f"**Review:** {md(v.get('review') or 'not reviewed')}", "",
                       f"![{md(v['title'])}](../diagrams/{v['id']}.svg)", "",
                       f"**Canonical IDs:** {ids}", "", f"**Scope and omissions:** {md(v['scope'])}", "",
                       f"Source: [`{v['source_path']}`](../../../{v['source_path']}) · renderer `{views.RENDERER}`", "",
                       *([f"**Broken reference:** {', '.join(unknown)} not in the spec."] if unknown else [])])
    p.write("views/index.md", lines)


def cockpit(p, catalog):
    """docs/README.md: the questions a reader asks, in the playbook's order, with honest states."""
    project, model = p.spec["project"], p.model
    open_decisions = [n for n in model.active("Decision") if n["data"]["answer"] is None]
    gen = GENERATED.name
    lines = [NOTICE, "", f"# {md(project['name'])}: documentation cockpit", "",
             f"Scope: {md(project['description'])}", "",
             f"Specification baseline: `{model.digest}` ({project['mode']}, `axiomspec/0.1`, `AX-CORE-0.1`)  ",
             f"Documentation build: `{GENERATOR}`, regenerate with `tools/axiom/axiom docs`  ",
             f"Design readiness: **{p.result.phase(DESIGN_GATES)}** (gates G01-G07; see [verification]({gen}/verification/index.md))",
             "", "## Start here", "",
             f"- [Intent, goals and actors]({gen}/product/overview.md)",
             f"- [Requirements, constraints and state models]({gen}/product/requirements.md)",
             f"- [Terms]({gen}/product/terms.md) · [Decisions and assumptions]({gen}/product/decisions.md)",
             f"- [Components, risks and controls]({gen}/system/components.md)",
             f"- [Verification and evidence]({gen}/verification/index.md) · [Traceability]({gen}/traceability.md)",
             f"- [All diagram views]({gen}/views/index.md)", "", "## Decisions needing attention", ""]
    if open_decisions:
        lines += ["| Decision | Question | Blocking | Governs |", "| --- | --- | --- | --- |"]
        lines += [f"| [{d['id']}]({gen}/product/decisions.md#{anchor(d['id'])}) | "
                  f"{md(d['data']['question'])} | {'yes' if d['data']['blocking'] else 'no'} | "
                  f"{', '.join(model.linked(d['id'], 'governs')) or '-'} |" for d in open_decisions]
    else:
        lines.append("No open decision.")
    lines += ["", "## Views", ""]
    if catalog["views"]:
        lines += ["| View | Kind | Claim | Question |", "| --- | --- | --- | --- |"]
        lines += [f"| [{md(v['title'])}]({gen}/views/{v['id']}.md) | {v['kind']} | {v['claim']} | {md(v['question'])} |"
                  for v in catalog["views"]]
    else:
        lines.append("No view yet: add one to `docs/view-catalog.json` with its source in `docs/views/`.")
    counts = {}
    for n in p.spec["nodes"]:
        counts[n["kind"]] = counts.get(n["kind"], 0) + 1
    lines += ["", "## Evidence and limits", "",
              "| Subject | Honest state |", "| --- | --- |",
              "| Artifact structure | " + ("pass" if p.result.gate_status("G01") == "pass" else "fail") + " (G01) |",
              f"| Business decisions | {len(open_decisions)} open |",
              f"| Formal semantics | G03 {p.result.gate_status('G03')}, G06 {p.result.gate_status('G06')} on declared scenarios |",
              f"| Product tests | {len(_receipts(p.root))} receipt(s); freshness: `tools/axiom/axiom evidence check` |",
              "| Operational behaviour | not observed (G13 unsupported) |", "",
              "Contents: " + ", ".join(f"{v} {k}" for k, v in sorted(counts.items())) + ".", ""]
    return "\n".join(lines).rstrip() + "\n"


def outputs(root, spec, model, result):
    """Every generated file: pages, diagrams, the cockpit and the manifest that names their inputs."""
    pages = build_pages(root, model, result)
    catalog = views.catalog(root)
    files = {f"{GENERATED.as_posix()}/{rel}": text for rel, text in pages.outputs.items()}
    files.update(views.rendered(root, model))
    files[COCKPIT.as_posix()] = cockpit(pages, catalog)
    inputs = {SPEC_PATH.as_posix(): model.digest}
    for rel in [VIEW_CATALOG.as_posix(), *[v["source_path"] for v in catalog["views"]]]:
        if (Path(root) / rel).is_file():
            inputs[rel] = sha256((Path(root) / rel).read_bytes())
    for receipt in sorted((Path(root) / EVIDENCE_DIR).glob("*.json")) if (Path(root) / EVIDENCE_DIR).is_dir() else []:
        inputs[receipt.relative_to(root).as_posix()] = sha256(receipt.read_bytes())
    manifest = {"format": "aeion-docs-manifest/0.1", "generator": GENERATOR, "renderer": views.RENDERER,
                "inputs": dict(sorted(inputs.items())),
                "outputs": {rel: sha256(text.encode("utf-8")) for rel, text in sorted(files.items())},
                "limitations": ["Views are documentation; canonical meaning is spec.json.",
                                "Layout is deterministic, not optimal; viewers may render fonts differently."]}
    files[f"{GENERATED.as_posix()}/manifest.json"] = pretty(manifest)
    return files


def generate(root, spec, model, result, check=False):
    """Write every output atomically, or with check list what differs. Returns problems."""
    if spec is None or model is None:
        return [f"docs: {SPEC_PATH} missing or invalid; run tools/axiom/axiom validate"]
    try:
        files = outputs(root, spec, model, result)
    except (views.ViewError, InputError) as error:
        return [f"docs: {error}"]
    root = Path(root)
    generated = root / GENERATED
    listed = views.listed_outputs(root)

    def owned(rel):
        return rel in files or views.generator_owns(root, rel, listed)
    existing = {p.relative_to(root).as_posix() for p in generated.rglob("*")
                if p.is_file() and not incidental(root, p, owned)} if generated.is_dir() else set()
    cockpit_path = root / COCKPIT
    if check:
        problems = []
        for rel, text in sorted(files.items()):
            path = root / rel
            if not path.is_file():
                problems.append(f"docs: {rel} is missing (run tools/axiom/axiom docs)")
            elif path.read_text(encoding="utf-8") != text:
                problems.append(f"docs: {rel} is stale or edited by hand (run tools/axiom/axiom docs)")
        problems += [f"docs: {rel} is not produced by the generator" for rel in sorted(existing - set(files))]
        return problems
    # Publish only over what the generator owns: a cockpit with its notice, a generated tree with its manifest.
    foreign = foreign_outputs(root)
    if foreign:
        return foreign
    # Publish: build the new tree beside the old one, then swap, so readers never see half of it.
    staging = generated.with_name(f".{generated.name}.new-{os.getpid()}")
    shutil.rmtree(staging, ignore_errors=True)
    for rel, text in files.items():
        if rel.startswith(GENERATED.as_posix() + "/"):
            write_atomic(staging / rel[len(GENERATED.as_posix()) + 1:], text)
    retired = generated.with_name(f".{generated.name}.old-{os.getpid()}")
    if generated.exists():
        os.replace(generated, retired)
    os.replace(staging, generated)
    shutil.rmtree(retired, ignore_errors=True)
    write_atomic(cockpit_path, files[COCKPIT.as_posix()])
    return []


def edited_original(name):
    """The file an editor's backup (X~), vim swap (.X.swp, .swo, .swx) or emacs autosave (#X#) belongs to."""
    if len(name) > 1 and name.endswith("~"):
        return name[:-1]
    if len(name) > 5 and name.startswith(".") and name.endswith((".swp", ".swo", ".swx")):
        return name[1:-4]
    if len(name) > 2 and name.startswith("#") and name.endswith("#"):
        return name[1:-1]
    return None


def incidental(root, path, owned):
    """Never a project's content, so regeneration may drop it: a file the desktop writes on its own
    (project_files.SKIPPED_FILES), the toolkit's own interrupted temporary file, and an editor's backup, swap
    or autosave of a file the generator wrote (owned(rel)). An editor file of anything else is the project's,
    like every other file the generator did not write, dot-named or not, and is never deleted."""
    name = path.name
    if name in SKIPPED_FILES or name.startswith(TEMP_PREFIX):
        return True
    original = edited_original(name)
    return bool(original) and owned((path.parent / original).relative_to(root).as_posix())


def foreign_outputs(root):
    """Problems for project files the generator would replace but did not write: a docs/README.md without the
    generator's notice, or a non-empty docs/generated/ without its manifest. Never overwritten, never deleted."""
    root, problems = Path(root), []
    cockpit = root / COCKPIT
    if cockpit.is_file() and not cockpit.read_text(encoding="utf-8", errors="replace").startswith(NOTICE):
        problems.append(f"docs: {COCKPIT} exists and was not generated; move it (for example to docs/authored/) "
                        "before the cockpit is written there")
    generated = root / GENERATED
    if generated.is_dir():
        listed = views.listed_outputs(root)

        def owned(rel):
            return views.generator_owns(root, rel, listed)
        foreign = sorted(rel for rel in (p.relative_to(root).as_posix() for p in generated.rglob("*")
                                         if p.is_file() and not incidental(root, p, owned))
                         if not owned(rel))
        if foreign:
            problems.append(f"docs: {GENERATED}/ holds files the generator did not write ({', '.join(foreign[:3])}"
                            f"{', …' if len(foreign) > 3 else ''}); move them before generating")
    return problems


def dangling_ids(root, model, spec_path=None):
    """Canonical IDs that knowledge/ and docs/ cite in prose or `spec_ids` but the spec does not hold."""
    if model is None:
        return []
    import graph
    snapshot = graph.snapshot(root, Path(spec_path) if spec_path else Path(root) / SPEC_PATH)
    dangling = snapshot["manifest"]["spec"].get("dangling_mentions", {})
    return [f"{rel}: cites {', '.join(ids)}, not in knowledge/spec/spec.json" for rel, ids in sorted(dangling.items())]


def init(root, spec_path, name, owner_role):
    """A draft product skeleton, empty catalogs and an idea brief; never overwrites an existing file."""
    root = Path(root)
    name = name or root.name
    files = {
        spec_path: pretty({
            "format": "axiomspec/0.1", "profile": "AX-CORE-0.1",
            "project": {"id": "PROJECT-001", "name": name, "owner": "ACTOR-001", "mode": "product",
                        "description": "Draft specification: replace with the product's purpose and first scope."},
            "actors": [{"id": "ACTOR-001", "name": owner_role, "type": "human_role", "binding_status": "asserted"},
                       {"id": "ACTOR-002", "name": "Coding agent", "type": "ai", "binding_status": "asserted"}],
            "sources": [{"id": "SRC-001", "type": "user_input", "locator": "docs/authored/brief.md",
                         "capture_sha256": None, "review_state": "unreviewed"}],
            "environments": [], "nodes": [], "edges": [], "bindings": [], "context_assets": []}),
        root / VIEW_CATALOG: pretty({"format": views.CATALOG_FORMAT, "views": []}),
        root / FEATURE_CATALOG: pretty({"format": FEATURE_FORMAT, "features": []}),
        root / "docs/authored/brief.md": BRIEF.format(name=name),
    }
    for path, text in files.items():
        if Path(path).exists():
            print(f"kept {Path(path).relative_to(root) if Path(path).is_relative_to(root) else path} (exists)")
            continue
        write_atomic(path, text)
        print(f"wrote {Path(path).relative_to(root) if Path(path).is_relative_to(root) else path}")
    # Generate the first cockpit now, so a fresh project passes `axiom check` from the start; an existing
    # project's own docs/README.md or docs/generated/ is reported, never replaced.
    import spec as specs
    result = specs.Result()
    loaded = specs.load_spec(spec_path, result)
    foreign = foreign_outputs(root)
    if foreign:
        print("\n".join(foreign))
        return 1
    if loaded is None:
        # The skeleton could not be read back (a missing schema, for one): say why, never a quiet success.
        for d in result.diagnostics:
            print(f"{d['gate']} {d['status']} {d['code']}: {d['message']}")
        return 4
    model, _ = specs.validate(loaded, result=result)
    problems = generate(root, loaded, model, result)
    if problems:
        print("\n".join(problems))
        return 1
    print("wrote docs/README.md and docs/generated/")
    print("next: fill docs/authored/brief.md, add goals and requirements to knowledge/spec/spec.json, then "
          "tools/axiom/axiom validate && tools/axiom/axiom docs")
    return 0


